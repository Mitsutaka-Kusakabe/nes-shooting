"""
Generate assets/chr.s for MOJAxMOJA WARS
2bpp NES CHR tile generator from ASCII art grids ('.'=0, '1'=1, '2'=2, '3'=3)
"""

def grid_to_tile(rows):
    assert len(rows) == 8, f"Expected 8 rows, got {len(rows)}"
    lo_bytes = []
    hi_bytes = []
    for r in rows:
        assert len(r) == 8, f"Expected 8 cols in '{r}'"
        lo = 0
        hi = 0
        for c in r:
            v = 0 if c == '.' else int(c)
            lo = (lo << 1) | (v & 1)
            hi = (hi << 1) | ((v >> 1) & 1)
        lo_bytes.append(lo)
        hi_bytes.append(hi)
    return lo_bytes + hi_bytes

def split_16x16(rows16):
    assert len(rows16) == 16
    for r in rows16:
        assert len(r) == 16, f"Row len {len(r)}: {r}"
    tl = [r[:8] for r in rows16[:8]]
    tr = [r[8:] for r in rows16[:8]]
    bl = [r[:8] for r in rows16[8:]]
    br = [r[8:] for r in rows16[8:]]
    return [grid_to_tile(tl), grid_to_tile(tr), grid_to_tile(bl), grid_to_tile(br)]

def split_32x32(rows32):
    assert len(rows32) == 32
    tiles = []
    for ty in range(4):
        for tx in range(4):
            sub = [rows32[ty*8 + y][tx*8:(tx+1)*8] for y in range(8)]
            tiles.append(grid_to_tile(sub))
    return tiles

tiles = [[0]*16 for _ in range(128)]  # $00-$7F (128 tiles; $80-$BF is font.s)

def set_tile(idx, rows8):
    tiles[idx] = grid_to_tile(rows8)

def set_16x16(base_idx, rows16):
    parts = split_16x16(rows16)
    for i, p in enumerate(parts):
        tiles[base_idx + i] = p

def split_16x24(rows24):
    assert len(rows24) == 24
    for r in rows24:
        assert len(r) == 16, f"Row len {len(r)}: {r}"
    out = []
    for ty in range(3):
        for tx in range(2):
            sub = [rows24[ty*8 + y][tx*8:(tx+1)*8] for y in range(8)]
            out.append(grid_to_tile(sub))
    return out

def set_16x24(base_idx, rows24):
    parts = split_16x24(rows24)
    for i, p in enumerate(parts):
        tiles[base_idx + i] = p

